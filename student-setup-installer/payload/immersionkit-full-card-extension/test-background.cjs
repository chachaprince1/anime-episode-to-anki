const {readFileSync} = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const fields = ['Custom front', 'Custom back', 'Metadata'];
let stored = {}, calls = [], listener, duplicates = [];
const context = vm.createContext({TextEncoder, URL, AbortController, setTimeout, clearTimeout, console, fetch: async (_, opts) => {
  const call = JSON.parse(opts.body); calls.push(call);
  const responses = { modelNames:['Custom'], modelFieldNames:fields, deckNames:['Target'], createDeck:1, findNotes:duplicates, storeMediaFile:call.params.filename, addNote:123, guiBrowse:[456], guiSelectCard:true };
  return {ok:true, json:async()=>({result:responses[call.action], error:null})};
}, chrome:{storage:{local:{get:async()=>stored,set:async value=>{stored=value;}}},runtime:{onMessage:{addListener:fn=>{listener=fn;}}}}});
vm.runInContext(readFileSync(__dirname+'/background-v192.js','utf8'),context);
const request = message => new Promise(resolve=>listener(message,{},resolve));
(async()=>{
  const fieldMap = {sentence:fields[0], translation:fields[1], furigana:fields[1], image:fields[1], audio:fields[1], id:fields[2], source:fields[2], url:fields[2]};
  assert.equal((await request({type:'configure',deck:'Target',model:'Custom',fieldMap,skipPreview:true,useOriginalAnkiOnly:true})).ok,true);
  assert.equal(stored.setup.fieldMap.audio,'Custom back');
  assert.equal(stored.setup.skipPreview,true);
  assert.equal(stored.setup.useOriginalAnkiOnly,true);
  const old = stored;
  assert.equal((await request({type:'configure',deck:'New',createDeck:true,model:'Custom',fieldMap:{...fieldMap,audio:'Gone'}})).ok,false);
  assert.equal(stored,old); assert(!calls.some(c=>c.action==='createDeck'));
  const data = {sentence:'猫 <cat>', translation:'A cat',furigana:'ねこ',imageUrl:'https://www.immersionkit.com/test.jpg',audioUrl:'https://www.immersionkit.com/test.mp3',id:'stable',source:'A show',url:'https://www.immersionkit.com/dictionary'};
  assert.equal((await request({type:'add',data})).ok,true);
  const note = calls.find(c=>c.action==='addNote').params.note;
  assert.equal(note.fields['Custom front'],'猫 &lt;cat&gt;');
  assert.match(note.fields['Custom back'],/A cat<br>ねこ<br><img.*<br>\[sound:/);
  assert.match(note.fields.Metadata,/stable<br>A show<br>https/);
  duplicates=[123]; calls=[];
  const duplicate = await request({type:'add',data});
  assert.equal(duplicate.ok,true);
  assert.equal(JSON.stringify(duplicate.result),JSON.stringify({noteId:123,deck:'Target',alreadyExists:true}));
  assert(!calls.some(c=>c.action==='storeMediaFile'));
  const existing = await request({type:'findExisting',data});
  assert.equal(existing.result.noteId,123);
  const viewed = await request({type:'view',noteId:123});
  assert.equal(viewed.ok,true);
  assert.equal(calls.find(c=>c.action==='guiBrowse').params.query,'nid:123');
  assert.equal(calls.find(c=>c.action==='guiSelectCard').params.card,456);
  console.log('PASS: mappings, preview preference, escaping, duplicate handling, and exact Anki navigation.');
})().catch(error=>{console.error(error);process.exitCode=1;});
